import os
import glob
import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder

# Configuration
RAW_DIR = "data/raw"
PROCESSED_DIR = "data/processed"
NUM_CLIENTS = 3  # Number of simulated federated learning clients

def load_and_clean_data(raw_dir):
    print("Loading parquet files...")
    file_paths = glob.glob(os.path.join(raw_dir, "*.parquet"))
    
    if not file_paths:
        raise FileNotFoundError(f"No .parquet files found in {raw_dir}. Please check your raw dataset directory.")
    
    # Load and concatenate all daily datasets
    df_list = [pd.read_parquet(file) for file in file_paths]
    df = pd.concat(df_list, ignore_index=True)
    
    print(f"Original dataset shape: {df.shape}")
    
    # Clean column names (strip whitespace)
    df.columns = df.columns.str.strip()
    
    # Handle missing and infinite values generated by network capturing tools
    print("Cleaning infinite and missing values...")
    df.replace([np.inf, -np.inf], np.nan, inplace=True)
    df.dropna(inplace=True)
    
    return df

def process_and_partition(df, num_clients, processed_dir):
    print("Encoding labels and scaling features...")
    
    # Separate features (X) and labels (y) - CICIDS2017 uses 'Label'
    if 'Label' not in df.columns:
        raise KeyError("Column 'Label' not found in dataset columns. Check dataset schema.")
        
    X = df.drop(columns=['Label'])
    y = df['Label']
    
    # Encode text labels into integers (e.g., Benign = 0, Attack = 1)
    encoder = LabelEncoder()
    y_encoded = encoder.fit_transform(y)
    
    # Scale numerical features (crucial for neural network convergence)
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)
    
    # Create a global test set (20%) to evaluate the central server model
    X_train, X_test, y_train, y_test = train_test_split(
        X_scaled, y_encoded, test_size=0.2, random_state=42, stratify=y_encoded
    )
    
    # Ensure processed directory exists
    os.makedirs(processed_dir, exist_ok=True)
    
    # Save the global test set
    pd.DataFrame(X_test).assign(Label=y_test).to_parquet(
        os.path.join(processed_dir, "global_test.parquet"), index=False
    )
    
    # Partition the remaining training data among the federated clients
    print(f"Partitioning training data into {num_clients} clients...")
    client_data_size = len(X_train) // num_clients
    
    for i in range(num_clients):
        start_idx = i * client_data_size
        # For the last client, assign all remaining data
        end_idx = (i + 1) * client_data_size if i != num_clients - 1 else len(X_train)
        
        X_client = X_train[start_idx:end_idx]
        y_client = y_train[start_idx:end_idx]
        
        # Save client partitions
        client_df = pd.DataFrame(X_client).assign(Label=y_client)
        client_file = os.path.join(processed_dir, f"client_{i+1}_train.parquet")
        client_df.to_parquet(client_file, index=False)
        print(f"Saved {client_file} with shape {client_df.shape}")
        
    print("Data pipeline complete!")

if __name__ == "__main__":
    dataset = load_and_clean_data(RAW_DIR)
    process_and_partition(dataset, NUM_CLIENTS, PROCESSED_DIR)
